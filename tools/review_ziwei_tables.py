"""Transcribe and compare the five source charts without repairing their text."""
import json,math,hashlib,re
from collect import ROOT
SOURCE='原文/ziwei/chapters/ziwei-db430d6a02.txt'
# Independently transcribed palace lists from the visible two-line vertical cells.
TABLES={
2:[[8,9],[10,11],[12,13],[14,15],[6,7,30],[16,17],[4,5,28,29],[18,19],[2,3,26,27],[1,24,25],[22,23],[20,21]],
3:[[4,12,14],[7,15,17],[10,18,20],[13,21,23],[1,9,11],[16,24,26],[6,8],[19,27,29],[3,9],[2,28],[25],[22,30]],
4:[[6,16,19,25],[10,20,23,29],[14,24,27],[18,28],[2,12,15,21],[22],[8,11,17],[26],[4,7,13],[3,9],[5],[1]],
5:[[8,20,24],[1,13,25,29],[6,18,30],[11,23],[3,15,19,27],[16,28],[10,14,22],[21],[5,9,17],[4,12],[7],[2,26]],
6:[[10,24,29],[2,16,30],[8,22],[14,28],[4,18,23],[1,20],[12,17,27],[7,26],[6,11,21],[5,15,25],[9,19],[3,13]]}
PALACES=list('巳午未申辰酉卯戌寅丑子亥')
def main():
    p=ROOT/SOURCE;lines=p.read_text(encoding='utf-8').splitlines();rows=[]
    for n,cells in TABLES.items():
        occurrences={d:[b for b,ds in zip(PALACES,cells) if d in ds] for d in range(1,31)}
        for d in range(1,31):
            q=math.ceil(d/n);pad=n*q-d;expected='寅卯辰巳午未申酉戌亥子丑'[(q-1+(pad if pad%2==0 else -pad))%12]
            actual=occurrences[d]
            rows.append({'局':n,'日':d,'原图宫':actual,'约定算法宫':expected,'一致':actual==[expected]})
    diffs=[r for r in rows if not r['一致']]
    report={'method':'人工按图逐格转录；公式以寅起、商减一、补数偶进奇退，非预测校验','source':SOURCE,'source_sha256':hashlib.sha256(p.read_bytes()).hexdigest(),'rows':rows,'differences':diffs}
    (ROOT/'验收/紫微五局逐日对照.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
    # Outline preserves every line in the two long units; autogenerated anchors are not study claims.
    records=json.loads((ROOT/'目录/chapters.json').read_text(encoding='utf-8'));index=[]
    for title in ['安身命例','一 命宫']:
        r=next(x for x in records if x['book']=='ziwei' and x['chapter']==title);a=(ROOT/r['path']).read_text(encoding='utf-8').splitlines()
        if title=='安身命例':
            starts=[0]+[i for i,l in enumerate(a) if l.strip() and not l.startswith((' ','|','-')) and (len(l)<45 and l.startswith(('安','定','论','六十','起五行')))]
            starts+= [216,244,272,300,328,356,383,410,437]
        else:
            pattern=r'^(紫微土|天机属木|太阳火|武曲金|天同水|廉贞属火|天府土|太阴水|贪狼属木|巨门水|天相水|天梁属土|七杀火金|破军水|文昌金|文曲水|左辅土|右弼水|禄存土|魁钺火|擎羊火金|陀罗火金|火星，|铃星火|地劫火|天空乃|天伤水|天使水|天马火|化禄星|化权星|化科星|化忌星|岁君火|斗君，)'
            starts=[i for i,l in enumerate(a) if re.match(pattern,l) or re.match(r'^\S{2,12}入(?:男命|女命|命限|命|限|男命).*诀[：:]$',l)]
        starts=sorted(set(starts))
        for j,start in enumerate(starts):
            end=starts[j+1] if j+1<len(starts) else len(a)
            index.append({'chapter':title,'path':r['path'],'start_line':start+1,'end_line':end,'anchor':a[start][:60]})
    (ROOT/'目录/紫微长篇索引.json').write_text(json.dumps(index,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps({'indexed_sections':len(index),'compared_days':len(rows),'differences':diffs},ensure_ascii=False))
if __name__=='__main__':main()
